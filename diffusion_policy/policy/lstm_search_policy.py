"""LSTM policy for open-loop, autoregressive candidate search on the maze (harine/openloop).

Ported from `harine/pushT`'s `lstm_bc_policy.py` (PPO's obs encoder -> LSTM -> MLP -> Gaussian
with a state-independent log_std) and changed in three ways that the open-loop experiment needs:

  * ONE ACTION PER STEP. The head emits a single (dx, dy) and the env is stepped before the next
    one, so a candidate is a full trajectory produced autoregressively rather than a chunk.
  * ACTION FEEDBACK. The LSTM input at step t is [obs features, previous realized displacement,
    context vector]. The displacement is what the env actually did (walls stop a move), which is
    also what the expert's actions are, so teacher forcing and rollout agree.
  * SEARCH CONTEXT. `max_actions > 1` turns this into a sequential-search (ST) policy: candidate k
    conditions on the realized trajectories and verifier values of candidates 0..k-1 through a
    pooled context vector. `max_actions == 1` is the best-of-N arm (no context).

Training contexts are generated by the same torch rollout (`rollout_step_torch`, stop at
`stop_radius`) that the eval harness mirrors with `MazeEnv.rollout_delta`, so the policy is
trained on exactly the context format it is evaluated with.
"""
from typing import Any, Dict, Optional

import torch
import torch.nn as nn
from torch.distributions import Normal
from diffusers.schedulers.scheduling_ddpm import DDPMScheduler

from diffusion_policy.common.pytorch_util import dict_apply
from diffusion_policy.model.common.normalizer import LinearNormalizer
from diffusion_policy.policy.base_image_policy import BaseImagePolicy
from diffusion_policy.common.maze_verifier import (
    MazeVerifier,
    build_images_torch,
    rollout_step_torch,
    snap_cardinal_torch,
)


class LSTMSearchPolicy(BaseImagePolicy):
    def __init__(self,
            shape_meta: Dict[str, Any],
            obs_encoder: nn.Module,
            horizon: int,
            n_action_steps: int,
            n_obs_steps: int,
            max_actions: int = 8,
            stop_radius: float = 1.0,
            lstm_hidden_size: int = 256,
            n_lstm_layers: int = 1,
            net_arch=(256, 256),
            obs_proj_dim: int = 256,
            context_dim: int = 128,
            log_std_init: float = -1.0,
            log_std_min: float = -2.0,
            obs_noise: str = 'none',
            obs_noise_sigma: float = 0.1,
            snap_cardinal: bool = False,
            **kwargs):
        super().__init__()
        action_shape = shape_meta['action']['shape']
        assert len(action_shape) == 1
        action_dim = action_shape[0]
        assert n_obs_steps == 1, 'the LSTM ticks once per env step; use n_obs_steps=1'
        assert obs_noise in ('none', 'gaussian', 'ddpm100'), obs_noise

        self.obs_encoder = obs_encoder
        self.horizon = horizon            # candidate trajectory length (context tensor width)
        self.n_action_steps = n_action_steps
        self.n_obs_steps = n_obs_steps
        self.action_dim = action_dim
        self.max_actions = max_actions
        self.stop_radius = stop_radius
        # snap every executed action to a unit cardinal move (one decision = one BFS step); the
        # eval harness reads this flag so rollout semantics are identical at train and eval
        self.snap_cardinal = bool(snap_cardinal)
        self.context_dim = context_dim
        self.obs_feature_dim = obs_encoder.output_shape()[0]
        self.normalizer = LinearNormalizer()
        self.kwargs = kwargs
        self.verifier = MazeVerifier(
            maze_path=kwargs.get('maze_path', None),
            device=kwargs.get('device', 'cpu'),
            noise=kwargs.get('verifier_noise', 0.0),
        )

        self.obs_proj = nn.Sequential(nn.Linear(self.obs_feature_dim, obs_proj_dim), nn.ReLU())
        # per-candidate embedding of [realized trajectory (horizon*Da), value], pooled over the
        # candidates seen so far (mean and max), then projected; zeros when there is no context
        self.ctx_cand = nn.Sequential(nn.Linear(horizon * action_dim + 1, context_dim), nn.ReLU())
        self.ctx_pool = nn.Linear(2 * context_dim, context_dim)

        self.lstm = nn.LSTM(
            input_size=obs_proj_dim + action_dim + context_dim,
            hidden_size=lstm_hidden_size,
            num_layers=n_lstm_layers,
            batch_first=True)
        layers, last = [], lstm_hidden_size
        for hidden in net_arch:
            layers += [nn.Linear(last, hidden), nn.Tanh()]
            last = hidden
        self.trunk = nn.Sequential(*layers)
        self.mean_head = nn.Linear(last, action_dim)
        # state-independent log_std (SB3's DiagGaussian); the floor keeps candidates distinct
        self.log_std = nn.Parameter(torch.full((action_dim,), float(log_std_init)))
        self.log_std_min = float(log_std_min)

        self.obs_noise = obs_noise
        self.obs_noise_sigma = float(obs_noise_sigma)
        self.obs_noise_scheduler = DDPMScheduler(
            num_train_timesteps=100, beta_start=0.001, beta_end=0.02, prediction_type='epsilon')

        self._state = None

    # ------------------------------------------------------------------ pieces
    def _std(self):
        return self.log_std.clamp_min(self.log_std_min).exp()

    def _apply_obs_noise(self, feat):
        # applied at train AND rollout time (same as dst_fuzzy's corrupt_obs_features), so the
        # policy sees the same input distribution in both
        if self.obs_noise == 'none':
            return feat
        noise = torch.randn_like(feat)
        if self.obs_noise == 'gaussian':
            return feat + self.obs_noise_sigma * noise
        timesteps = torch.randint(0, self.obs_noise_scheduler.config.num_train_timesteps,
                                  (feat.shape[0],), device=feat.device).long()
        return self.obs_noise_scheduler.add_noise(feat, noise, timesteps)

    def _obs_features(self, nobs_flat):
        """(N, obs_proj_dim) from a dict of normalized (N, ...) observations."""
        feat = self.obs_encoder(nobs_flat)
        feat = self._apply_obs_noise(feat)
        return self.obs_proj(feat)

    def _context_vector(self, ctx_nactions, ctx_values, ctx_mask):
        """(B, S, context_dim) from (B, K, H, Da) normalized realized actions, (B, K) values
        and a (B, S, K) bool mask saying which candidates each of the S slots may see."""
        B, S, K = ctx_mask.shape
        if K == 0:
            return torch.zeros((B, S, self.context_dim), device=ctx_mask.device)
        flat = torch.cat([ctx_nactions.reshape(B, K, -1), (ctx_values / self.horizon)[..., None]], dim=-1)
        emb = self.ctx_cand(flat)                                            # (B, K, C)
        m = ctx_mask.to(emb.dtype)[..., None]                                # (B, S, K, 1)
        emb = emb[:, None]                                                   # (B, 1, K, C)
        count = m.sum(dim=2).clamp_min(1.0)
        mean = (emb * m).sum(dim=2) / count
        neg = torch.finfo(emb.dtype).min
        mx = torch.where(m > 0, emb, torch.full_like(emb, neg)).amax(dim=2)
        mx = torch.where(m.sum(dim=2) > 0, mx, torch.zeros_like(mx))
        out = self.ctx_pool(torch.cat([mean, mx], dim=-1))
        return torch.where(m.sum(dim=2) > 0, out, torch.zeros_like(out))

    def _prefix_masks(self, K, device):
        """(K+1, K): slot k sees candidates j < k."""
        return torch.arange(K, device=device)[None, :] < torch.arange(K + 1, device=device)[:, None]

    def _dist(self, latent):
        return Normal(self.mean_head(self.trunk(latent)), self._std())

    # ------------------------------------------------------------------ rollout (torch env)
    def _rollout_one(self, free, start, goal, ctx_vec, max_steps):
        """Autoregressive rollout of one candidate per row, stepping `rollout_step_torch`.

        ctx_vec: (B, context_dim). Returns sampled (B, T, Da) raw, traj (B, T+1, 2), done_step (B,).
        Rows freeze once within stop_radius of the goal (eval's success rule).
        """
        B = start.shape[0]
        device = start.device
        pos = start.float()
        goal = goal.float()
        done = torch.zeros(B, dtype=torch.bool, device=device)
        done_step = torch.full((B,), -1, dtype=torch.long, device=device)
        prev_naction = torch.zeros((B, self.action_dim), device=device)
        state = None
        sampled = torch.zeros((B, max_steps, self.action_dim), device=device)
        traj = [pos]
        for t in range(max_steps):
            obs = {
                'image': build_images_torch(free, pos, goal),
                'agent_pos': pos,
                'goal_pos': goal,
            }
            nobs = self.normalizer.normalize(obs)
            feat = self._obs_features(nobs)
            inp = torch.cat([feat, prev_naction, ctx_vec], dim=-1)[:, None]
            latent, state = self.lstm(inp, state)
            naction = self._dist(latent[:, 0]).sample()
            action = self.normalizer['action'].unnormalize(naction)
            if self.snap_cardinal:
                action = snap_cardinal_torch(action)
            sampled[:, t] = torch.where(done[:, None], torch.zeros_like(action), action)
            nxt = rollout_step_torch(free, pos, action)
            new_pos = torch.where(done[:, None], pos, nxt)
            prev_naction = self.normalizer['action'].normalize(new_pos - pos)
            pos = new_pos
            traj.append(pos)
            reached = ~done & ((pos - goal).norm(dim=-1) <= self.stop_radius)
            done_step = torch.where(reached, torch.full_like(done_step, t + 1), done_step)
            done = done | reached
            if bool(done.all()):
                break
        traj = torch.stack(traj, dim=1)
        if traj.shape[1] < max_steps + 1:
            pad = traj[:, -1:].expand(-1, max_steps + 1 - traj.shape[1], -1)
            traj = torch.cat([traj, pad], dim=1)
        return sampled, traj, done_step

    @torch.inference_mode()
    def rollout_candidates_torch(self, free, start, goal, n_candidates, max_steps=None, iid=False):
        """N candidates per row, in the torch env. Sequential (context of 0..k-1) unless `iid`.

        Returns dict: sampled (B,N,T,Da), realized (B,N,T,Da), traj (B,N,T+1,2), done_step (B,N),
        values (B,N) = -BFS(final, goal).
        """
        T = self.horizon if max_steps is None else max_steps
        B = start.shape[0]
        device = start.device
        dist_field, unreachable = self.verifier._goal_distance_field_torch(free, goal)

        def value_of(final_pos):
            return -self.verifier._sample_goal_distance_torch(free, dist_field, final_pos, unreachable)

        if iid:
            N = n_candidates
            rep = lambda x: x.repeat_interleave(N, dim=0)
            ctx = torch.zeros((B * N, self.context_dim), device=device)
            sampled, traj, done_step = self._rollout_one(rep(free), rep(start), rep(goal), ctx, T)
            rep_field = dist_field.repeat_interleave(N, dim=0)
            values = -self.verifier._sample_goal_distance_torch(rep(free), rep_field, traj[:, -1], unreachable)
            unrep = lambda x: x.reshape(B, N, *x.shape[1:])
            traj = unrep(traj)
            return {
                'sampled': unrep(sampled), 'realized': traj[:, :, 1:] - traj[:, :, :-1],
                'traj': traj, 'done_step': unrep(done_step), 'values': unrep(values),
            }

        out = {k: [] for k in ('sampled', 'realized', 'traj', 'done_step', 'values')}
        window = max(self.max_actions - 1, 1)  # beyond max_actions the context slides (eval does too)
        for k in range(n_candidates):
            if k == 0:
                ctx = torch.zeros((B, self.context_dim), device=device)
            else:
                realized = torch.stack(out['realized'][-window:], dim=1)
                values = torch.stack(out['values'][-window:], dim=1)
                nreal = self.normalizer['action'].normalize(realized)
                mask = torch.ones((B, 1, realized.shape[1]), dtype=torch.bool, device=device)
                ctx = self._context_vector(nreal, values, mask)[:, 0]
            sampled, traj, done_step = self._rollout_one(free, start, goal, ctx, T)
            out['sampled'].append(sampled)
            out['realized'].append(traj[:, 1:] - traj[:, :-1])
            out['traj'].append(traj)
            out['done_step'].append(done_step)
            out['values'].append(value_of(traj[:, -1]))
        return {key: torch.stack(v, dim=1) for key, v in out.items()}

    # ------------------------------------------------------------------ training
    def compute_loss(self, batch):
        """Teacher-forced NLL of the expert's next action at every step, for every context slot."""
        nobs = self.normalizer.normalize(batch['obs'])
        nactions = self.normalizer['action'].normalize(batch['action'])
        B, T, Da = nactions.shape
        assert Da == self.action_dim
        mask = batch.get('attention_mask', None)
        if mask is None:
            mask = torch.ones((B, T), dtype=nactions.dtype, device=nactions.device)
        mask = mask.to(nactions.dtype)

        # (B, T, F) observation features; the expert's realized displacement is its action
        flat = dict_apply(nobs, lambda x: x.reshape(-1, *x.shape[2:]))
        feat = self._obs_features(flat).reshape(B, T, -1)
        prev = torch.cat([torch.zeros_like(nactions[:, :1]), nactions[:, :-1]], dim=1)

        K = self.max_actions - 1
        if K > 0:
            image = batch['obs']['image']
            free = image[:, 0, 0] < 0.5
            start = batch['obs']['agent_pos'][:, 0]
            goal = batch['obs']['goal_pos'][:, 0]
            self.eval()
            cands = self.rollout_candidates_torch(free, start, goal, K)
        # train mode whenever this loss will be backpropagated: cuDNN's RNN backward requires it,
        # and the workspace leaves the policy in eval() after each epoch's validation pass
        self.train(torch.is_grad_enabled())
        if K > 0:
            nreal = self.normalizer['action'].normalize(cands['realized'])
            prefix = self._prefix_masks(K, nactions.device)[None].expand(B, -1, -1)
            ctx = self._context_vector(nreal, cands['values'], prefix)        # (B, K+1, C)
        else:
            ctx = torch.zeros((B, 1, self.context_dim), device=nactions.device)
        S = ctx.shape[1]

        feat_s = feat[:, None].expand(-1, S, -1, -1)
        prev_s = prev[:, None].expand(-1, S, -1, -1)
        ctx_s = ctx[:, :, None, :].expand(-1, -1, T, -1)
        inp = torch.cat([feat_s, prev_s, ctx_s], dim=-1).reshape(B * S, T, -1)
        latent, _ = self.lstm(inp)
        log_prob = self._dist(latent).log_prob(nactions[:, None].expand(-1, S, -1, -1).reshape(B * S, T, Da))
        log_prob = log_prob.sum(dim=-1).reshape(B, S, T)
        m = mask[:, None].expand(-1, S, -1)
        return -(log_prob * m).sum() / m.sum().clamp_min(1.0)

    # ------------------------------------------------------------------ rollout (real env)
    def reset(self):
        self._state = None

    def predict_step(self, obs_dict, prev_action, context_actions=None, context_values=None):
        """One env step: raw obs (B, To, ...) -> raw (dx, dy), carrying the LSTM state.

        prev_action: (B, Da) raw displacement realized at the previous step (zeros at t=0).
        context_actions / context_values: (B, K, horizon, Da) raw realized trajectories of the
        earlier candidates and their values; None or K=0 for the first / best-of-N candidate.
        """
        obs_dict = {k: v[:, -1] for k, v in obs_dict.items() if k != 'attention_mask'}
        nobs = self.normalizer.normalize(obs_dict)
        feat = self._obs_features(nobs)
        B = feat.shape[0]
        prev_naction = self.normalizer['action'].normalize(prev_action)
        if context_actions is None or context_actions.shape[1] == 0:
            ctx = torch.zeros((B, self.context_dim), device=feat.device)
        else:
            nreal = self.normalizer['action'].normalize(context_actions)
            mask = torch.ones((B, 1, context_actions.shape[1]), dtype=torch.bool, device=feat.device)
            ctx = self._context_vector(nreal, context_values, mask)[:, 0]
        inp = torch.cat([feat, prev_naction, ctx], dim=-1)[:, None]
        latent, self._state = self.lstm(inp, self._state)
        naction = self._dist(latent[:, 0]).sample()
        action = self.normalizer['action'].unnormalize(naction)
        return snap_cardinal_torch(action) if self.snap_cardinal else action

    @torch.inference_mode()
    def predict_action(self, obs_dict, verifier=None, n_actions=None):
        """Workspace sample-block form: (sampled (B, N, horizon, Da), values (B, N)) of N candidates
        rolled out in the torch env from the batch's first frame. The eval harness uses
        `predict_step` instead; this exists for the train_action_mse / train_action_value logs."""
        n_actions = self.max_actions if n_actions is None else n_actions
        image = obs_dict['image']
        free = image[:, 0, 0] < 0.5
        start = obs_dict['agent_pos'][:, 0]
        goal = obs_dict['goal_pos'][:, 0]
        cands = self.rollout_candidates_torch(free, start, goal, n_actions, iid=self.max_actions == 1)
        return cands['sampled'], cands['values']

    def set_normalizer(self, normalizer: LinearNormalizer):
        self.normalizer.load_state_dict(normalizer.state_dict())
