#!/usr/bin/env python3
"""Consolidate the rmse_v2 comparison into one markdown doc:
  1. rmse_v2 search-policy SR per 10k checkpoint (action-normalized, val=testset).
  2. BC baseline (argmax, best-by-N=1 checkpoint) -> data/eval/bc_v2_det/.
  3. Before vs after the normalize-context-actions change: old rmse-loss search
     (rmse_det, no action-norm, sub50) vs new rmse_v2 (sub50), matched 10k/20k.

All SR eval: 50 ep, MODE=argmax, DQC-chunk verifier, seeds 1000-1049. Re-run any
time; reflects whatever cells have finished.
  python scripts/simpler/analysis/gen_rmse_v2_results.py
"""
import json, glob, re, collections, os

OUT = "data/eval/rmse_v2_det/RESULTS.md"
NS = [1, 2, 4, 8, 16, 32, 64]
CKS = ["10k", "20k", "30k", "40k", "50k"]
TASKS = ["eggplant", "stack", "spoon"]
DEMOS = ["sub100", "sub50"]


def sr(f):
    try:
        return json.load(open(f)).get("success_rate")
    except Exception:
        return None


def cell(v):
    return f"{v:.2f}" if isinstance(v, (int, float)) else "–"


def best(d):
    xs = [(d[n], n) for n in NS if isinstance(d.get(n), (int, float))]
    return max(xs) if xs else (None, None)


# 1. rmse_v2 search per checkpoint
V2 = collections.defaultdict(dict)   # (ck, task_demos) -> {N: sr}
for f in glob.glob("data/eval/rmse_v2_det/rmse_v2_*/*/sr_n*/eval_log.json"):
    m = re.search(r"rmse_v2_det/rmse_v2_(.+?)/(\d+k)/sr_n(\d+)/", f)
    if m:
        V2[(m.group(2), m.group(1))][int(m.group(3))] = sr(f)

# 2. BC argmax (best-N=1 ckpt)
BC = collections.defaultdict(dict)   # task_demos -> {N: sr}
for f in glob.glob("data/eval/bc_v2_det/*/argmax_n*/eval_log.json"):
    m = re.search(r"bc_v2_det/(.+?)/argmax_n(\d+)/", f)
    if m:
        BC[m.group(1)][int(m.group(2))] = sr(f)

# 2b. BC softmax (archived, same n_obs=1 policies, best-N=1 ckpt) — older stochastic
BC_SOFT = collections.defaultdict(dict)
BC_SOFT_CK = {}
_ARCH = ("/gscratch/robotics/harine/RoboMonkey_relocated/data/"
         "archive_gpu_stochastic/bc_dqc_chunk")
for f in glob.glob(_ARCH + "/*nobs1*softmax*/eval_log.json"):
    lab = f.split("/")[-2]
    m = re.search(r"bcH8(spoon_|stack_)?sub(\d+)nobs1_(\d+k)_.*_n(\d+)_", lab)
    if not m:
        continue
    task = (m.group(1) or "eggplant_").rstrip("_")
    demos = f"sub{m.group(2)}"
    if demos == "sub25":
        continue
    key = f"{task}_{demos}"
    BC_SOFT[key][int(m.group(4))] = sr(f)
    BC_SOFT_CK[key] = m.group(3)

# 3. old rmse-loss search (rmse_det, sub50, no action-norm)
OLD = collections.defaultdict(dict)  # (ck, task) -> {N: sr}
for f in glob.glob("data/eval/rmse_det/rmse_*/*/sr_n*/eval_log.json"):
    m = re.search(r"rmse_det/rmse_(\w+?)/(\d+k)/sr_n(\d+)/", f)
    if m:
        OLD[(m.group(2), m.group(1))][int(m.group(3))] = sr(f)

# 0. VERSION 0 (pre-normalization) full BoN matrix — parsed from the preserved file
V0 = collections.defaultdict(dict)   # (task_demos) -> {ckint: {N: sr}}
V0_FILE = "data/eval/rmse_v2_det/v0_pre_normalization_bon_matrix.md"
if os.path.exists(V0_FILE):
    for line in open(V0_FILE):
        if "diff" not in line or "(sub" not in line:
            continue
        tk = next((t for t in TASKS if t in line), None)
        md = re.search(r"\(sub(\d+)-div", line)
        mc = re.search(r"(\d+)k\b", line)
        if not (tk and md and mc):
            continue
        nums = [int(c.strip()) for c in line.split("|") if re.fullmatch(r"\d+", c.strip())]
        if len(nums) >= 7:
            V0[f"{tk}_sub{md.group(1)}"][int(mc.group(1))] = {
                n: v / 100.0 for n, v in zip(NS, nums[:7])}

L = []
L.append("# rmse_v2 retrained search policies — SR eval + BC baseline + before/after\n")
L.append("Retrained sub100/sub50 **rmse-loss diffusion search** policies (all train demos used; "
         "**val = held-out testset**), 50k steps, with the *normalize-context-actions* change "
         "(commit 7f06736, 2026-07-30) + dropout-restore fix. Deterministic SR: 50 ep, tiled(8), "
         "**MODE=argmax**, seeds 1000-1049, frozen DQC-chunk verifier. N=1 = base policy (no search); "
         "N>1 = best-of-N by the verifier. Auto-generated by `scripts/simpler/analysis/gen_rmse_v2_results.py`.\n")
L.append("_50k = final model (`latest.ckpt`); training caps at 50000 without a 50k-boundary step-ckpt._\n")
L.append("_**Version 0** (pre-normalization) SR is in §5 below, preserved in "
         "`v0_pre_normalization_bon_matrix.md`._\n")

# ---- Section 1: search per checkpoint ----
L.append("\n## 1. Search-policy SR per checkpoint (rmse_v2, action-normalized)\n")
order = [f"{t}_{d}" for t in TASKS for d in DEMOS]
for ck in CKS:
    present = [r for r in order if (ck, r) in V2]
    if not present:
        continue
    L.append(f"\n### {ck}\n")
    L.append("| run | " + " | ".join(f"N={n}" for n in NS) + " | best (N) |")
    L.append("|" + "---|" * (len(NS) + 2))
    for r in present:
        d = V2[(ck, r)]
        b, bn = best(d)
        L.append(f"| {r} | " + " | ".join(cell(d.get(n)) for n in NS) +
                 f" | {cell(b)}" + (f" (N={bn})" if bn else "") + " |")

# ---- Section 2: BC baseline (argmax + softmax) ----
L.append("\n## 2. BC baseline (best-by-N=1 checkpoint)\n")
L.append("Data-matched `n_obs=1` BC denoisers (the control the search policy must beat), "
         "same DQC verifier, ddpm candidates. **argmax** = apples-to-apples with §1; "
         "**softmax** = archived (temp-1.0 pool resampling, older stochastic eval regime).\n")

L.append("\n### 2a. argmax\n")
if any(BC.values()):
    L.append("| BC policy | " + " | ".join(f"N={n}" for n in NS) + " | best (N) |")
    L.append("|" + "---|" * (len(NS) + 2))
    for r in order:
        if r not in BC:
            continue
        d = BC[r]; b, bn = best(d)
        L.append(f"| {r} | " + " | ".join(cell(d.get(n)) for n in NS) +
                 f" | {cell(b)}" + (f" (N={bn})" if bn else "") + " |")
    L.append(f"\n_BC argmax cells present: {sum(len(v) for v in BC.values())}/42._\n")
else:
    L.append("_BC argmax eval still running (launch_bc_v2_argmax.sh)._\n")

L.append("\n### 2b. softmax (archived)\n")
if any(BC_SOFT.values()):
    L.append("| BC policy | ckpt | " + " | ".join(f"N={n}" for n in NS) + " | best (N) |")
    L.append("|" + "---|" * (len(NS) + 3))
    for r in order:
        if r not in BC_SOFT:
            continue
        d = BC_SOFT[r]; b, bn = best(d)
        L.append(f"| {r} | {BC_SOFT_CK.get(r,'?')} | " + " | ".join(cell(d.get(n)) for n in NS) +
                 f" | {cell(b)}" + (f" (N={bn})" if bn else "") + " |")
else:
    L.append("_archived softmax BC evals not found._\n")

# ---- Section 3: OLD rmse-loss search SR (pre action-normalization), raw ----
L.append("\n## 3. Old rmse-loss search SR (pre normalize-context-actions, sub50)\n")
L.append("The old rmse-loss search policies (trained Jul 1-8, before commit 7f06736), "
         "`rmse_det`. Same argmax / DQC / 50-ep protocol, sub50, checkpoints 10k/20k. "
         "Raw SR for your own comparison to §1.\n")
for ck in ["10k", "20k"]:
    present = [t for t in TASKS if (ck, t) in OLD]
    if not present:
        continue
    L.append(f"\n### {ck} (sub50, old)\n")
    L.append("| task | " + " | ".join(f"N={n}" for n in NS) + " | best (N) |")
    L.append("|" + "---|" * (len(NS) + 2))
    for t in present:
        d = OLD[(ck, t)]; b, bn = best(d)
        L.append(f"| {t} | " + " | ".join(cell(d.get(n)) for n in NS) +
                 f" | {cell(b)}" + (f" (N={bn})" if bn else "") + " |")

# ---- Section 4: previously-published late-checkpoint headline (det_results.md) ----
# The old sub50 rmse-loss SEARCH policies at their LATE checkpoints (eggplant/spoon
# 90k, stack 60k), argmax, from data/eval/det_results.md — the numbers reported
# before this campaign. Checkpoints differ from rmse_v2 (50k); reference only.
PREV = {
    "eggplant": ("90k", {1: .68, 2: .66, 4: .70, 8: .78, 16: .62, 32: .64, 64: .60}),
    "stack":    ("60k", {1: .20, 2: .26, 4: .32, 8: .30, 16: .28, 32: .30, 64: .38}),
    "spoon":    ("90k", {1: .26, 2: .30, 4: .32, 8: .38, 16: .42, 32: .44, 64: .36}),
}
L.append("\n## 4. Previously-published headline (late-ckpt, sub50, search argmax)\n")
L.append("The old rmse-loss search policies at their LATE checkpoints (from "
         "`det_results.md`), the numbers reported before this campaign. Reference "
         "only — checkpoints differ from §1 (rmse_v2 is 50k).\n")
L.append("| task | ckpt | " + " | ".join(f"N={n}" for n in NS) + " | best (N) |")
L.append("|" + "---|" * (len(NS) + 3))
for t in TASKS:
    ck, d = PREV[t]
    b, bn = best(d)
    L.append(f"| {t} | {ck} | " + " | ".join(cell(d.get(n)) for n in NS) +
             f" | {cell(b)} (N={bn}) |")

# ---- Section 5: Version 0 (pre-normalization) full BoN matrix ----
L.append("\n## 5. Version 0 (pre-normalization) — full Best-of-N matrix\n")
L.append("The pre-normalization search policies (`diff_search_rmse_*_diverse`, before "
         "commit 7f06736) — the full SR-vs-N sweep across checkpoints. **Preserved in "
         "`v0_pre_normalization_bon_matrix.md` (do not delete).** softmax / older eval "
         "regime, so N=1 is the clean match to the argmax §1; N>1 mixes selection.\n")
v0order = [f"{t}_{d}" for t in TASKS for d in ("sub100", "sub50")]
for r in v0order:
    if r not in V0:
        continue
    L.append(f"\n### {r} (v0)\n")
    L.append("| ckpt | " + " | ".join(f"N={n}" for n in NS) + " | best (N) |")
    L.append("|" + "---|" * (len(NS) + 2))
    for ckint in sorted(V0[r]):
        d = V0[r][ckint]; b, bn = best(d)
        L.append(f"| {ckint}k | " + " | ".join(cell(d.get(n)) for n in NS) +
                 f" | {cell(b)}" + (f" (N={bn})" if bn else "") + " |")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(L) + "\n")
tot = sum(len(v) for v in V2.values())
print(f"wrote {OUT}  (search {tot} cells, BC {sum(len(v) for v in BC.values())} cells, "
      f"old {sum(len(v) for v in OLD.values())} cells)")
