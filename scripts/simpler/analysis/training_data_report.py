#!/usr/bin/env python3
"""Training-data provenance + success count + start-position scatter.

Reads the eggplant training Zarr shards (ground truth) to:
  - count trajectories and SUCCESS trajectories (success = any reward==1 in episode;
    rewards are sparse 0/1 for the SimplerEnv eggplant task),
  - extract per-trajectory START positions (eggplant / basket / end-effector at the
    first timestep) and scatter them,
  - summarize the seed provenance.

Only small arrays are touched (episode_ends, rewards, *_pose); the big
agentview_image array is never loaded.

Seed provenance (from openvla-mini/.../collect_trajectories.py defaults):
  ep_seed = start_seed(100000) + global_idx,  start_index=0, target=10000/shard.
  Training shards (state0,state1) draw from the 100000-block; the disjoint VAL set
  used start_index=50000 -> 150000-block. Collection was resumable (state0 log shows
  a resume at existing_episodes=1759), so the exact realized seed multiset is not
  recoverable from metadata (per-episode seeds are not stored). What is certain:
  training seeds live in [100000, 109999].

Run (needs zarr+matplotlib, e.g. the monkey-verifier env):
  python scripts/simpler/analysis/training_data_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import zarr

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "data" / "eval" / "_verifier_comparison"
DATA_ROOT = Path("/gscratch/robotics/harine/data/eggplant_in_basket_complete")
SHARDS = ["state0.zarr", "state1.zarr"]
START_SEED = 100_000

ENTITIES = [
    ("data/obs/insertive_asset_pose", "eggplant (insertive)"),
    ("data/obs/receptive_asset_pose", "basket (receptive)"),
    ("data/obs/end_effector_pose", "end-effector"),
]


def analyze_shard(path: Path):
    z = zarr.open(str(path), mode="r")
    ends = np.asarray(z["meta/episode_ends"][:], dtype=np.int64)
    starts = np.concatenate([[0], ends[:-1]]).astype(np.int64)
    rewards = np.asarray(z["data/rewards"][:], dtype=np.float32)
    n_ep = len(ends)

    success = np.zeros(n_ep, dtype=bool)
    for i, (s, e) in enumerate(zip(starts, ends)):
        if e > s:
            success[i] = bool(np.any(rewards[s:e] > 0.5))

    poses = {}
    for key, _ in ENTITIES:
        arr = z[key]
        poses[key] = np.asarray(arr.oindex[starts.tolist(), :3]) if hasattr(arr, "oindex") \
            else np.asarray(arr[:])[starts, :3]
    return {
        "n_ep": int(n_ep),
        "n_success": int(success.sum()),
        "success": success,
        "starts_idx": starts,
        "poses": poses,
    }


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    results = {}
    for shard in SHARDS:
        p = DATA_ROOT / shard
        if not p.exists():
            print(f"[warn] missing {p}")
            continue
        print(f"[read] {p} ...")
        results[shard] = analyze_shard(p)
        r = results[shard]
        print(f"  episodes={r['n_ep']}  success={r['n_success']} "
              f"({100.0*r['n_success']/r['n_ep']:.1f}%)")

    tot_ep = sum(r["n_ep"] for r in results.values())
    tot_su = sum(r["n_success"] for r in results.values())

    # ---- markdown report ---------------------------------------------------
    L = []
    L.append("# Training-data report — eggplant (`widowx_put_eggplant_in_basket`)\n")
    L.append(f"Dataset: `{DATA_ROOT}` (symlinks state0.zarr, state1.zarr). "
             "Auto-generated by `scripts/simpler/analysis/training_data_report.py`.\n")
    L.append("## Trajectory & success counts (success = any reward==1; sparse 0/1)\n")
    L.append("| shard | trajectories | successes | success rate |")
    L.append("|---|---|---|---|")
    for shard, r in results.items():
        L.append(f"| {shard} | {r['n_ep']} | {r['n_success']} | "
                 f"{100.0*r['n_success']/r['n_ep']:.1f}% |")
    L.append(f"| **total** | **{tot_ep}** | **{tot_su}** | "
             f"**{100.0*tot_su/tot_ep:.1f}%** |\n")
    L.append("## Seeds used to generate the training data\n")
    L.append("- Formula: `ep_seed = start_seed + global_idx`, with `start_seed=100000`, "
             "`start_index=0`, target 10000 episodes/shard "
             "(`collect_trajectories.py:369`, defaults L92-94).")
    L.append("- Both training shards draw seeds from the **100000-block** "
             "`[100000, 109999]`. A single uninterrupted run would map the i-th episode "
             "to seed `100000+i`.")
    L.append("- Collection was **resumable** (state0 log shows a resume at "
             "`existing_episodes=1759`) and per-episode seeds are **not stored** in the "
             "zarr, so the exact realized seed multiset is not recoverable from metadata.")
    L.append("- The **validation** set (`eggplant_in_basket_val/val*.zarr`) used a "
             "disjoint range: `start_index=50000` → seeds `150000-150999`.\n")
    (OUT / "training_data_report.md").write_text("\n".join(L))
    print(f"[md] wrote {OUT/'training_data_report.md'}")

    (OUT / "training_data_report.json").write_text(json.dumps(
        {shard: {"n_ep": r["n_ep"], "n_success": r["n_success"]}
         for shard, r in results.items()} | {"total_ep": tot_ep, "total_success": tot_su},
        indent=2))

    # ---- start-position scatter -------------------------------------------
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception as e:
        print(f"[plot] matplotlib unavailable ({e}); skipping figure.")
        return

    # Two-color SUCCESS vs FAIL scatter (Okabe-Ito colorblind-safe, distinct,
    # semi-transparent). Object start poses sit on a DISCRETE grid (~26 eggplant
    # cells, ~1 basket, 1 EE) so success/fail would overdraw — we add a small
    # jitter (≈1-2 mm) and randomize z-order so both classes stay visible.
    from matplotlib.lines import Line2D
    C_SUCC = "#0072B2"  # blue
    C_FAIL = "#D55E00"  # vermillion
    rng = np.random.default_rng(0)
    fig, axes = plt.subplots(1, 3, figsize=(16, 5.4))
    for ax, (key, title) in zip(axes, ENTITIES):
        sx = np.concatenate([results[s]["poses"][key][:, 0] for s in results])
        sy = np.concatenate([results[s]["poses"][key][:, 1] for s in results])
        succ = np.concatenate([results[s]["success"] for s in results]).astype(bool)
        jx = max(0.0012, 0.015 * float(np.ptp(sx)))
        jy = max(0.0012, 0.015 * float(np.ptp(sy)))
        px = sx + rng.normal(0, jx, sx.shape)
        py = sy + rng.normal(0, jy, sy.shape)
        cols = np.where(succ, C_SUCC, C_FAIL)
        order = rng.permutation(len(px))            # fair z-order (no class on top)
        ax.scatter(px[order], py[order], s=14, c=cols[order], alpha=0.35, linewidths=0)
        ncell = np.unique(np.round(np.stack([sx, sy], 1) / 1e-3).astype(np.int64),
                          axis=0).shape[0]
        ax.set_title(f"{title}  (n={len(sx)}, {ncell} cells @1mm)")
        ax.set_xlabel("x (m)"); ax.set_ylabel("y (m)")
        ax.grid(True, alpha=0.3)
        handles = [
            Line2D([0], [0], marker="o", linestyle="", color=C_SUCC,
                   label=f"success ({int(succ.sum())})"),
            Line2D([0], [0], marker="o", linestyle="", color=C_FAIL,
                   label=f"fail ({int((~succ).sum())})"),
        ]
        ax.legend(handles=handles, fontsize=8, loc="best", markerscale=1.4)
    fig.suptitle(f"Training-trajectory start positions — eggplant "
                 f"({tot_su}/{tot_ep} success = {100.0*tot_su/tot_ep:.1f}%); "
                 f"success=blue, fail=vermillion (jittered ≈1-2 mm for visibility)",
                 fontsize=12)
    fig.tight_layout(rect=[0, 0, 1, 0.95])
    out_png = OUT / "training_start_positions.png"
    fig.savefig(out_png, dpi=120)
    print(f"[plot] wrote {out_png}")


if __name__ == "__main__":
    main()
